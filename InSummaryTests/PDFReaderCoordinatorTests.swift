    // MARK: - Behaviour 5: round-trip across coordinator re-init

    /// After the user toggles the pagination preference and the
    /// coordinator is discarded, a fresh coordinator opened against the
    /// same persisted document must honour the persisted value. This is
    /// the preference-round-trip contract from
    /// `openspec/changes/pdf-reader-pencilkit-ink-recovery/specs/pdf-engine/spec.md`
    /// "Round-trip across coordinator re-init".
    func test_paginationModeRoundTripsAcrossCoordinatorReInit() throws {
        let document = makeSeedDocument()
        document.paginationModeRaw = "horizontal"
        let container = makeSchemaContainer()
        let context = ModelContext(container)
        context.insert(document)
        try context.save()

        do {
            let coordinator = try PDFReaderCoordinator(document: document, modelContext: context)
            coordinator.paginationMode = .vertical
        }

        let reloaded = try XCTUnwrap(
            try container.mainContext.fetch(FetchDescriptor<DocumentItem>()).first,
            "The seed DocumentItem must survive a save / fetch round-trip"
        )
        XCTAssertEqual(
            reloaded.paginationModeRaw,
            "vertical",
            "Toggling the coordinator must persist paginationModeRaw = \"vertical\"; got \"\(reloaded.paginationModeRaw)\""
        )

        let rehydratedContext = ModelContext(container)
        let coordinator = try PDFReaderCoordinator(document: reloaded, modelContext: rehydratedContext)
        XCTAssertEqual(
            coordinator.pdfView.displayMode,
            .singlePageContinuous,
            "Re-initialised coordinator must apply vertical PDFDisplayMode; got \(coordinator.pdfView.displayMode)"
        )
        XCTAssertEqual(
            coordinator.pdfView.displayDirection,
            .vertical,
            "Re-initialised coordinator must apply vertical PDFDisplayDirection; got \(coordinator.pdfView.displayDirection)"
        )
    }

    // MARK: - Behaviour 6: only paginationModeRaw + updatedAt persist

    /// Toggling the pagination preference must persist only
    /// `paginationModeRaw` and `updatedAt` to the SwiftData row. Every
    /// other `DocumentItem` field must remain byte-equal across the
    /// toggle. This pins the Phase 1 invariant: the coordinator does not
    /// add, alter, default, or migrate any Phase 1 entity field.
    func test_onlyPaginationModeRawAndUpdatedAtPersistAcrossToggle() throws {
        let originalCreatedAt = Date(timeIntervalSince1970: 1_700_000_000)
        let originalUpdatedAt = Date(timeIntervalSince1970: 1_700_000_000)
        let originalLocator = Data([0x01, 0x02, 0x03])

        let document = DocumentItem()
        document.title = "Getting Started"
        document.fileTypeRaw = "pdf"
        document.fileExtension = "pdf"
        document.localFileName = ""
        document.fileSize = 12_345
        document.contentHash = "deadbeefcafebabe"
        document.lastReadLocator = originalLocator
        document.lastReadPageIndex = 4
        document.totalPages = 20
        document.paginationModeRaw = "horizontal"
        document.createdAt = originalCreatedAt
        document.updatedAt = originalUpdatedAt

        let container = makeSchemaContainer()
        let context = ModelContext(container)
        context.insert(document)
        try context.save()

        let coordinator = try PDFReaderCoordinator(document: document, modelContext: context)
        coordinator.paginationMode = .vertical
        try context.save()

        let reloaded = try XCTUnwrap(
            try container.mainContext.fetch(FetchDescriptor<DocumentItem>()).first,
            "The DocumentItem must round-trip through the container"
        )

        // Unchanged fields — must be byte-equal to the original values.
        XCTAssertEqual(reloaded.title, "Getting Started")
        XCTAssertEqual(reloaded.fileTypeRaw, "pdf")
        XCTAssertEqual(reloaded.fileExtension, "pdf")
        XCTAssertEqual(reloaded.localFileName, "")
        XCTAssertEqual(reloaded.fileSize, 12_345)
        XCTAssertEqual(reloaded.contentHash, "deadbeefcafebabe")
        XCTAssertEqual(reloaded.lastReadLocator, originalLocator)
        XCTAssertEqual(reloaded.lastReadPageIndex, 4)
        XCTAssertEqual(reloaded.totalPages, 20)
        XCTAssertEqual(reloaded.createdAt, originalCreatedAt)

        // Mutated fields — only `paginationModeRaw` + `updatedAt` may change.
        XCTAssertEqual(
            reloaded.paginationModeRaw,
            "vertical",
            "Toggling the coordinator must persist paginationModeRaw = \"vertical\""
        )
        XCTAssertGreaterThan(
            reloaded.updatedAt,
            originalUpdatedAt,
            "Toggling the coordinator must advance DocumentItem.updatedAt past the original value"
        )
    }

