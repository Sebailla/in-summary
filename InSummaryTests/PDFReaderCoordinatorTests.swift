    // MARK: - Behaviour 11: TRIANGULATE — setPaginationMode calls modelContext.save() and advances updatedAt

    /// TRIANGULATE (task 2.5): the `paginationMode` setter must call
    /// `modelContext.save()` so the new pagination preference and the
    /// advanced `updatedAt` are persisted atomically with the toggle,
    /// and the persisted write set must remain
    /// `{paginationModeRaw, updatedAt}` — every other `DocumentItem`
    /// field stays equal.
    ///
    /// This triangulation pins the persistence boundary from three
    /// angles that the existing behaviour 6
    /// (`test_onlyPaginationModeRawAndUpdatedAtPersistAcrossToggle`)
    /// does NOT cover:
    ///
    /// 1. **No explicit `try context.save()` in the test.** Behaviour 6
    ///    calls `try context.save()` *after* the setter, which means
    ///    the test passes even if the setter itself forgets to call
    ///    `save()`. Behaviour 11 deliberately OMITS that explicit
    ///    save, so the only way the mutations reach the backing store
    ///    is via the setter's own `try modelContext.save()` call.
    /// 2. **Fresh `ModelContext` fetch.** A fresh `ModelContext`
    ///    built from the same container has its own in-memory cache;
    ///    uncommitted mutations on `context` are NOT visible from
    ///    `verifyContext`. Observing the new `paginationModeRaw`
    ///    and `updatedAt` from a fresh fetch is a direct signal that
    ///    `save()` was called and the backing store reflects the
    ///    toggle. If the setter forgot the `save()`, this fetch
    ///    would return `paginationModeRaw == "horizontal"` (the
    ///    persisted baseline) and `updatedAt == originalUpdatedAt`.
    /// 3. **`modelContext.hasChanges == false` after the setter.**
    ///    The setter mutates the row then must drain those mutations
    ///    via `modelContext.save()`. If the setter forgot the
    ///    `save()`, `hasChanges` would still be `true`. A pre-toggle
    ///    baseline assertion guarantees the coordinator's `init`
    ///    does not author any uncommitted mutations that would
    ///    confound the post-toggle check.
    /// 4. **Every other field stays byte-equal.** The setter must
    ///    only mutate `{paginationModeRaw, updatedAt}`; every other
    ///    `DocumentItem` field must round-trip through the fresh
    ///    fetch equal to its pre-toggle value. This is the Phase 1
    ///    invariant: the coordinator does not add, alter, default,
    ///    or migrate any Phase 1 entity field.
    func test_setPaginationModeCallsModelContextSaveAndAdvancesUpdatedAtWhileOtherFieldsStayEqual() throws {
        let originalCreatedAt = Date(timeIntervalSince1970: 1_700_000_000)
        let originalUpdatedAt = Date(timeIntervalSince1970: 1_700_000_000)
        let originalLocator = Data([0x01, 0x02, 0x03])

        let document = DocumentItem()
        document.title = "Getting Started"
        document.fileTypeRaw = "pdf"
        document.fileExtension = "pdf"
        document.localFileName = ""
        document.fileSize = 12_345
        document.contentHash = "deadbeefcafebabe"
        document.lastReadLocator = originalLocator
        document.lastReadPageIndex = 4
        document.totalPages = 20
        document.paginationModeRaw = "horizontal"
        document.createdAt = originalCreatedAt
        document.updatedAt = originalUpdatedAt

        let container = makeSchemaContainer()
        let context = ModelContext(container)
        context.insert(document)
        try context.save()

        let coordinator = try PDFReaderCoordinator(document: document, modelContext: context)

        // Pre-toggle baseline: the modelContext must have no pending
        // changes after the coordinator's `init` + the explicit
        // baseline `save()`. If the `init` left any mutations
        // uncommitted, the post-toggle `hasChanges == false`
        // assertion below would falsely pass.
        XCTAssertFalse(
            context.hasChanges,
            "Before the setter: modelContext.hasChanges must be false (no pending mutations after init + baseline save)"
        )

        // The setter MUST call `modelContext.save()` to drain the
        // paginationModeRaw + updatedAt mutations it authors.
        // Unlike behaviour 6, this test does NOT call
        // `try context.save()` afterwards — the only path for the
        // mutations to reach the backing store is the setter's own
        // `try modelContext.save()` call.
        coordinator.paginationMode = .vertical

        // Triangulation angle #1: `modelContext.hasChanges` must be
        // false after the setter. The setter mutated
        // `paginationModeRaw` + `updatedAt`, then called
        // `modelContext.save()` to drain the pending changes. If
        // the setter forgot to call `save()`, `hasChanges` would
        // still be `true`.
        XCTAssertFalse(
            context.hasChanges,
            "After setPaginationMode: modelContext.hasChanges must be false — the setter must have called modelContext.save() to drain the pending paginationModeRaw + updatedAt mutations"
        )

        // Triangulation angle #2: a fresh `ModelContext` fetched
        // from the same container must observe the new persisted
        // state. The fresh context has its own in-memory cache;
        // uncommitted mutations on `context` are NOT visible from
        // `verifyContext`. If the setter did NOT call `save()`,
        // this fetch would return `paginationModeRaw == "horizontal"`
        // (the persisted baseline).
        let verifyContext = ModelContext(container)
        let reloaded = try XCTUnwrap(
            try verifyContext.fetch(FetchDescriptor<DocumentItem>()).first,
            "The DocumentItem must round-trip through the container"
        )

        // Mutated fields — exactly the documented write set.
        XCTAssertEqual(
            reloaded.paginationModeRaw,
            "vertical",
            "setPaginationMode must persist paginationModeRaw == \"vertical\"; a fresh fetch returning \"horizontal\" means the setter did not call modelContext.save()"
        )
        XCTAssertGreaterThan(
            reloaded.updatedAt,
            originalUpdatedAt,
            "setPaginationMode must advance DocumentItem.updatedAt past the original value"
        )

        // Unchanged fields — must be byte-equal to the original
        // values. The setter must NOT alter any field beyond the
        // documented `{paginationModeRaw, updatedAt}` write set.
        XCTAssertEqual(reloaded.title, "Getting Started")
        XCTAssertEqual(reloaded.fileTypeRaw, "pdf")
        XCTAssertEqual(reloaded.fileExtension, "pdf")
        XCTAssertEqual(reloaded.localFileName, "")
        XCTAssertEqual(reloaded.fileSize, 12_345)
        XCTAssertEqual(reloaded.contentHash, "deadbeefcafebabe")
        XCTAssertEqual(reloaded.lastReadLocator, originalLocator)
        XCTAssertEqual(reloaded.lastReadPageIndex, 4)
        XCTAssertEqual(reloaded.totalPages, 20)
        XCTAssertEqual(reloaded.createdAt, originalCreatedAt)
    }

    // MARK: - Helpers

    /// Builds a `DocumentItem` that satisfies the Phase 2 seed contract:
    /// `fileTypeRaw == "pdf"` AND `localFileName.isEmpty == true` AND
    /// `paginationModeRaw == "horizontal"`. Each test that needs a
    /// different starting state mutates the result before insertion.
    private func makeSeedDocument() -> DocumentItem {
        let document = DocumentItem()
        document.title = "Getting Started"
        document.fileTypeRaw = "pdf"
        document.fileExtension = "pdf"
        document.localFileName = ""
        document.paginationModeRaw = "horizontal"
        return document
    }

    /// Creates an empty on-disk directory and returns a `Bundle` rooted at
    /// it. Used by the "missing fixture" test to ensure the bundle
    /// resolution path cannot accidentally hit a resource that lives in
    /// the production app bundle.
    private func makeIsolatedBundle() throws -> Bundle {
        let tempDir = FileManager.default.temporaryDirectory
            .appendingPathComponent("PDFReaderCoordinatorTests-isolated-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(
            at: tempDir,
            withIntermediateDirectories: true
        )
        guard let bundle = Bundle(url: tempDir) else {
            throw NSError(
                domain: "PDFReaderCoordinatorTests",
                code: 1,
                userInfo: [NSLocalizedDescriptionKey: "Failed to construct isolated Bundle at \(tempDir.path)"]
            )
        }
        return bundle
    }

    /// Writes a file named `<resourceName>.pdf` containing bytes that
    /// are NOT a valid `PDFDocument` into a fresh on-disk directory and
    /// returns a `Bundle` rooted at that directory. Used by the
    /// "unreadable fixture" test to feed the coordinator malformed
    /// bytes that pass the resource-resolution step but fail at parse.
    private func makeBundleContainingJunkPDF(resourceName: String) throws -> Bundle {
        let tempDir = FileManager.default.temporaryDirectory
            .appendingPathComponent("PDFReaderCoordinatorTests-junk-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(
            at: tempDir,
            withIntermediateDirectories: true
        )
        let junkBytes = Data("this is not a valid PDF document".utf8)
        let junkURL = tempDir.appendingPathComponent("\(resourceName).pdf")
        try junkBytes.write(to: junkURL, options: .atomic)
        guard let bundle = Bundle(url: tempDir) else {
            throw NSError(
                domain: "PDFReaderCoordinatorTests",
                code: 2,
                userInfo: [NSLocalizedDescriptionKey: "Failed to construct junk Bundle at \(tempDir.path)"]
            )
        }
        return bundle
    }
