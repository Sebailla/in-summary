//
//  PDFReaderCoordinatorTests.swift
//  InSummaryTests
//
//  RED contract (task 2.1) for child PR #2 (`feat/pdf-engine`) inside the
//  Phase 2 chain `pdf-reader-pencilkit-ink-recovery`. Every test method
//  below pins one of the ten behaviours documented in
//  `openspec/changes/pdf-reader-pencilkit-ink-recovery/tasks.md` §2.1
//  and the corresponding scenario block in
//  `openspec/changes/pdf-reader-pencilkit-ink-recovery/specs/pdf-engine/spec.md`.
//
//  The behaviours encoded here, in the exact order they appear in the task
//  description, are:
//
//    1. The coordinator loads the bundled fixture into its `PDFView`.
//    2. Horizontal mode sets `displayMode = .singlePage` +
//       `displayDirection = .horizontal` + `usePageViewController(true)`.
//    3. Vertical mode sets `displayMode = .singlePageContinuous` +
//       `displayDirection = .vertical`.
//    4. Unknown `paginationModeRaw` falls back to horizontal paginated
//       settings.
//    5. `paginationModeRaw` round-trip preserves the value across a
//       coordinator re-init.
//    6. The coordinator persists only `paginationModeRaw` + `updatedAt` to
//       the SwiftData row; every other field stays equal.
//    7. Missing fixture surfaces `PDFReaderError.fixtureMissing(resource:)`.
//    8. Unreadable fixture surfaces `PDFReaderError.fixtureUnreadable`.
//    9. Non-PDF document surfaces `PDFReaderError.unsupportedDocument(reason:)`.
//   10. Document with non-empty `localFileName` surfaces
//       `PDFReaderError.unsupportedDocument(reason:)`.
//   11. (TRIANGULATE — task 2.5) `setPaginationMode` calls
//       `modelContext.save()` and the persisted row's `updatedAt`
//       advances while every other field stays equal. This
//       triangulation is the angle the existing behaviour 6 leaves
//       uncovered: behaviour 6 calls `try context.save()` itself
//       after the setter, so it cannot tell whether the setter
//       invoked `modelContext.save()` on its own. Behaviour 11
//       removes the explicit save, observes the persisted state via
//       a fresh `ModelContext`, and pins `hasChanges == false`
//       after the setter returns.
//
//  RED contract: this file is the failing test for the RED step. The
//  production types `PDFReaderCoordinator` and `PDFReaderError` are
//  intentionally absent in this slice, so every test below must fail at
//  compile time on the unresolved type references before any test method
//  ever executes. The compile failure is the strict-TDD RED signal — it
//  proves the test encodes the contract before the production code is
//  authored. GREEN belongs to task 2.2 (`PDFReaderError`) and task 2.3
//  (`PDFReaderCoordinator`); the RED snapshot stays byte-identical until
//  those tasks land.
//

